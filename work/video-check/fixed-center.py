from playwright.sync_api import sync_playwright
import json
from PIL import Image
with sync_playwright() as p:
 b=p.chromium.launch(headless=True,channel='chrome')
 page=b.new_page(viewport={'width':2200,'height':1400},device_scale_factor=1)
 page.goto('http://localhost:5173/scenedeck/?deck=digital-image-intro&slide=video-frames')
 page.wait_for_selector('.di-video__body[data-ready="true"]',timeout=15000)
 page.evaluate("""() => {let e=document.querySelector('.di-video');while(e){if(getComputedStyle(e).transform!=='none')e.style.transform='none';e=e.parentElement}}""")
 page.locator('.di-video').screenshot(path='work/video-check/fixed-center.png')
 before=page.locator('.di-video__hero').bounding_box()
 x1=page.locator('[data-preview-frame="90"]').bounding_box()['x']
 page.get_by_role('button',name='播放',exact=True).click()
 page.wait_for_function("Number(document.querySelector('.di-video__body').dataset.frame)>=78")
 page.get_by_role('button',name='暂停',exact=True).click()
 after=page.locator('.di-video__hero').bounding_box()
 x2=page.locator('[data-preview-frame="90"]').bounding_box()['x']
 assert before==after,(before,after)
 assert x2<x1-100,(x1,x2)
 print('Fixed center:',before,'Thumbnail leftward movement:',x1-x2)
 page.locator('.di-video').screenshot(path='work/video-check/fixed-center-playing.png')
 page.get_by_role('button',name='回到开头',exact=True).click()
 page.wait_for_function("document.querySelector('.di-video__body').dataset.frame==='0'")
 page.get_by_role('button',name='下一帧',exact=True).click()
 page.wait_for_function("document.querySelector('.di-video__body').dataset.frame==='1'")
 page.get_by_role('slider',name='帧序号',exact=True).fill('120')
 page.wait_for_function("document.querySelector('.di-video__body').dataset.frame==='120'")
 page.get_by_role('button',name='重播',exact=True).click()
 page.wait_for_function("Number(document.querySelector('.di-video__body').dataset.frame)<30 && document.querySelector('.di-video__body').dataset.playing==='true'")
 page.get_by_role('button',name='暂停',exact=True).click()
 print('bounds:',page.evaluate("""() => {const s=document.querySelector('.di-video'),b=s.getBoundingClientRect();return {size:[b.width,b.height],outside:[...s.querySelectorAll('*')].filter(e=>{const r=e.getBoundingClientRect();return r.width&&r.height&&(r.left<b.left-1||r.top<b.top-1||r.right>b.right+1||r.bottom>b.bottom+1)}).map(e=>e.className)}}"""))
 failed=b.new_page(viewport={'width':1600,'height':1000})
 failed.route('**/video_1791531788070.mp4',lambda route: route.abort())
 failed.goto('http://localhost:5173/scenedeck/?deck=digital-image-intro&slide=video-frames')
 failed.wait_for_selector('.di-video__fallback')
 failed.wait_for_function("document.querySelector('.di-video__fallback').naturalWidth>0")
 failed.get_by_role('slider',name='帧序号',exact=True).fill('30')
 failed.wait_for_function("document.querySelector('.di-video__fallback').src.endsWith('/030.jpg') && document.querySelector('.di-video__fallback').complete")
 print('MP4 failure fallback: real frame 30 visible')
 Image.open('work/video-check/fixed-center.png').resize((640,360),Image.Resampling.LANCZOS).save('assets/10da7e16-ff24-449a-9978-b74b99524e47/scenedeck-thumbnails/video-frames.png')
 b.close()
